const BY_ID = new Map(EXERCISE_TEMPLATES.map((e) => [e.id, e]));

/// Name → id, lower-cased. Workout history rows store the exercise NAME, so
/// this is the only way back to the template that knows its muscle group.
const BY_NAME = new Map(EXERCISE_TEMPLATES.map((e) => [e.name.toLowerCase(), e.id]));

export const getExercise = (id: string): ExerciseTemplate | undefined => BY_ID.get(id);

export const getAllExercises = (): ExerciseTemplate[] => EXERCISE_TEMPLATES;

export const hasExercise = (id: string): boolean => BY_ID.has(id);

export const getExercisesByType = (type: ExerciseTemplate['type']): ExerciseTemplate[] =>
  EXERCISE_TEMPLATES.filter((e) => e.type === type);

export const getExercisesByMuscleGroup = (muscle: string): ExerciseTemplate[] => {
  const q = muscle.toLowerCase();
  return EXERCISE_TEMPLATES.filter(
    (e) =>
      (e.targetMuscleGroup?.toLowerCase().includes(q) ?? false) ||
      (e.secondaryMuscleGroup?.toLowerCase().includes(q) ?? false),
  );
};

export const getUniversalIdFromExerciseName = (name: string): string | undefined =>
  BY_NAME.get(name.toLowerCase());
